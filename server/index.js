function extractField(html, fieldId) {
  const match = html.match(new RegExp(`id="${fieldId}"\\s+value="([^"]*)"`, 'i'));
  return match ? match[1] : '';
}

async function fetchAllStations() {
  const allStations = [];
  const seen = new Set();

  console.log('[puppeteer] Launching browser...');
  let browser;
  try {
    const executablePath = findChrome();
    browser = await puppeteer.launch({
      headless: true,
      executablePath,
      args: ['--no-sandbox', '--disable-setuid-sandbox', '--disable-dev-shm-usage', '--disable-gpu'],
    });

    const page = await browser.newPage();
    await page.setUserAgent('Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36');

    console.log('[puppeteer] Loading DWS page...');
    await page.goto(DWS_URL, { waitUntil: 'networkidle2', timeout: 45000 });

    for (const wma of WMA_TABS) {
      try {
        if (wma.btn !== 'Wma4') {
          console.log('[puppeteer] Clicking ' + wma.id + ' tab...');
          await page.evaluate((btn) => {
            const buttons = Array.from(document.querySelectorAll('button[name="wmaBttn"]'));
            const match = buttons.find(b => b.value === btn);
            if (match) match.click();
          }, wma.btn);
          await page.waitForNavigation({ waitUntil: 'networkidle2', timeout: 20000 }).catch(() => {});
          await new Promise(r => setTimeout(r, 1500));
        }
        const html = await page.content();
        const parsed = parseStations(html);
        console.log('[puppeteer] ' + wma.id + ': ' + parsed.length + ' stations');
        for (const s of parsed) {
          if (!seen.has(s.code)) { seen.add(s.code); allStations.push(s); }
        }
      } catch (err) {
        console.error('[puppeteer] ' + wma.id + ' failed:', err.message);
      }
    }
  } catch (err) {
    console.error('[puppeteer] Failed:', err.message);
    // Plain fetch fallback for WMA4 only
    try {
      const res = await fetch(DWS_URL, {
        headers: { 'User-Agent': 'Mozilla/5.0' },
        signal: AbortSignal.timeout(20000),
      });
      const html = await res.text();
      for (const s of parseStations(html)) {
        if (!seen.has(s.code)) { seen.add(s.code); allStations.push(s); }
      }
    } catch (e) { console.error('[fetch] Fallback failed:', e.message); }
  } finally {
    if (browser) await browser.close();
    console.log('[puppeteer] Browser closed.');
  }

  console.log('[puppeteer] Total stations: ' + allStations.length);
  return allStations;
}


// ── Background coord scraper ───────────────────────────────────────────────
// After main data fetch, quietly scrape coords for stations that are missing them
async function scrapeCoords(stations, page) {
  const missing = stations.filter(s => s.lat === null && s.detailId);
  if (!missing.length) return;
  console.log(`[coords] Scraping coords for ${missing.length} stations...`);

  let scraped = 0;
  for (const s of missing.slice(0, 30)) { // limit to 30 per run to avoid timeout
    try {
      const url = `${DWS_BASE}/Hydrology/Verified/HyDataSets.aspx?Station=${s.code}`;
      await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 10000 });
      const text = await page.evaluate(() => document.body.innerText);

      // Look for lat/lon pattern: e.g. "-26.877" "28.107" or "26:52:37" "28:06:24"
      const ddMatch = text.match(/(-\d{2}\.\d{2,4})\s+(\d{2}\.\d{2,4})/);
      const dmsMatch = text.match(/(\d{2}:\d{2}:\d{2})\s+(\d{2}:\d{2}:\d{2})/);

      if (ddMatch) {
        const lat = parseFloat(ddMatch[1]);
        const lon = parseFloat(ddMatch[2]);
        if (lat && lon && -35 < lat < -21 && 16 < lon < 34) {
          SCRAPED_COORDS[s.code] = [lat, lon];
          s.lat = lat; s.lng = lon;
          scraped++;
        }
      } else if (dmsMatch) {
        const parseDMS = (str, neg) => {
          const p = str.split(':');
          const v = parseInt(p[0]) + parseInt(p[1])/60 + parseFloat(p[2])/3600;
          return neg ? -v : v;
        };
        const lat = parseDMS(dmsMatch[1], true);
        const lon = parseDMS(dmsMatch[2], false);
        if (lat && lon && -35 < lat < -21 && 16 < lon < 34) {
          SCRAPED_COORDS[s.code] = [round4(lat), round4(lon)];
          s.lat = round4(lat); s.lng = round4(lon);
          scraped++;
        }
      }
      await new Promise(r => setTimeout(r, 300));
    } catch (_) { /* skip failed stations */ }
  }
  console.log(`[coords] Scraped ${scraped} new coordinates`);
}

function round4(n) { return Math.round(n * 10000) / 10000; }

async function getAllData(forceRefresh = false) {
  const key = 'ALL';
  const cached = cache[key];
  if (!forceRefresh && cached && (Date.now() - cached.timestamp < CACHE_TTL)) {
    return { ...cached.data, fromCache: true };
  }

  const allStations = await fetchAllStations();
  checkSpillAlerts(allStations);

  const wmas = {};
  for (const wma of WMA_TABS) {
    wmas[wma.id] = {
      label:    wma.label,
      stations: allStations.filter(s => s.wmaId === wma.id),
      bounds:   WMA_BOUNDS[wma.id],
      center:   WMA_CENTERS[wma.id],
    };
  }

  const data = {
    wmas, allStations, errors: {},
    fetchedAt: new Date().toISOString(),
    totalStations: allStations.length,
  };

  cache[key] = { data, timestamp: Date.now() };
  broadcastSSE('data-updated', {
    fetchedAt: data.fetchedAt,
    totalStations: data.totalStations,
    spillingCount: allStations.filter(s => s.spill > 0).length,
  });

  return { ...data, fromCache: false };
}

