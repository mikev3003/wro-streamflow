// ── Spill alerts ───────────────────────────────────────────────────────────
let prevSpilling = new Set();
function checkSpillAlerts(stations) {
  const nowSpilling = new Set(stations.filter(s => s.spill > 0).map(s => s.code));
  const newSpills   = [...nowSpilling].filter(c => !prevSpilling.has(c));
  const cleared     = [...prevSpilling].filter(c => !nowSpilling.has(c));
  if (newSpills.length) {
    broadcastSSE('spill-alert', {
      type: 'new',
      stations: stations.filter(s => newSpills.includes(s.code))
        .map(s => ({ code: s.code, place: s.place, spill: s.spill, flow: s.flow, wmaId: s.wmaId, wmaLabel: s.wmaLabel })),
      timestamp: new Date().toISOString(),
    });
  }
  if (cleared.length) {
    broadcastSSE('spill-cleared', { codes: cleared, timestamp: new Date().toISOString() });
  }
  prevSpilling = nowSpilling;
}

